namespace MC.Code.CLI.Application
{
    /// <summary>
    /// Defines the layout used to display application information.
    /// </summary>
    public enum ApplicationInfoLayout
    {
        /// <summary>
        /// Displays application information using the standard layout.
        /// </summary>
        Standard,

        /// <summary>
        /// Displays application information using a compact layout with reduced output.
        /// </summary>
        Compact,

        /// <summary>
        /// Displays application information using a detailed layout with additional output.
        /// </summary>
        Detailed
    }
}